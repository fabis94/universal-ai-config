import { readdir, readFile, stat } from "node:fs/promises";
import { basename, join, relative } from "node:path";
import { parseFrontmatter } from "./parser.js";

/** A skill discovered on disk: a directory containing a valid `SKILL.md`. */
export interface DiscoveredSkill {
  /** Kebab-cased skill name — used as the output template directory name */
  name: string;
  /** Description from frontmatter (empty string if absent) */
  description: string;
  /** Absolute path to the directory containing SKILL.md */
  dir: string;
  /** Path to the skill dir relative to the discovery root (e.g. `.claude/skills/foo`) */
  relPath: string;
}

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build", "__pycache__"]);
const MAX_DEPTH = 5;

/** Canonical uac template source directory — skills here are authored sources. */
const TEMPLATE_SOURCE_DIR = ".universal-ai-config";
/** The Agent Skills standard's folder (`.agents/skills`). */
const AGENT_SKILLS_ROOT = ".agents";
/** Per-tool skill folders — skills here are usually generated by uac. */
const TOOL_OUTPUT_DIRS = new Set([".claude", ".github", ".cursor", ".codex"]);

/**
 * What the installed copy has to be:
 *
 * - `templates`: a uac template, so a source repo's `.universal-ai-config`
 *   copy is the original and the tool folders hold generated copies.
 * - `standards`: a plain Agent Skills folder the tools read as it is (the
 *   project keeps its skills in `.agents/skills`), so a `.universal-ai-config`
 *   copy — EJS, universal frontmatter — is the last resort.
 */
export type SkillPreference = "templates" | "standards";

/**
 * Rank a skill directory by where it lives, so that when the same skill name is
 * found in multiple places the copy best suited to the install wins. Higher wins.
 */
function preferenceRank(dir: string, prefer: SkillPreference): number {
  const segments = dir.split(/[\\/]/);
  const inTemplates = segments.includes(TEMPLATE_SOURCE_DIR);
  const inStandard = segments.includes(AGENT_SKILLS_ROOT);
  const inTool = segments.some((segment) => TOOL_OUTPUT_DIRS.has(segment));
  if (prefer === "standards") {
    if (inTemplates) return 0;
    if (inStandard) return 3;
    return inTool ? 1 : 2;
  }
  if (inTemplates) return 2;
  return inTool || inStandard ? 0 : 1;
}

/** Normalize a skill name into a safe kebab-cased directory name. */
export function normalizeSkillName(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function hasSkillMd(dir: string): Promise<boolean> {
  try {
    return (await stat(join(dir, "SKILL.md"))).isFile();
  } catch {
    return false;
  }
}

/**
 * Collect directories containing a `SKILL.md`. A directory with a SKILL.md is
 * treated as a leaf skill — we do not descend into it (its subdirectories are
 * supporting files, not nested skills).
 */
async function findSkillDirs(dir: string, depth = 0): Promise<string[]> {
  if (depth > MAX_DEPTH) return [];
  if (await hasSkillMd(dir)) return [dir];

  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }

  const nested = await Promise.all(
    entries
      .filter((entry) => entry.isDirectory() && !SKIP_DIRS.has(entry.name))
      .map((entry) => findSkillDirs(join(dir, entry.name), depth + 1)),
  );
  return nested.flat();
}

async function readSkill(skillDir: string, rootDir: string): Promise<DiscoveredSkill | null> {
  let content: string;
  try {
    content = await readFile(join(skillDir, "SKILL.md"), "utf-8");
  } catch {
    return null;
  }

  const { frontmatter } = parseFrontmatter(content);
  const rawName = frontmatter.name;
  if (typeof rawName !== "string" || rawName.trim() === "") {
    return null;
  }

  const name = normalizeSkillName(rawName) || normalizeSkillName(basename(skillDir));
  if (!name) return null;

  const description = typeof frontmatter.description === "string" ? frontmatter.description : "";
  return { name, description, dir: skillDir, relPath: relative(rootDir, skillDir) };
}

/**
 * Discover all skills under `rootDir` (optionally scoped to `subpath`).
 * Results are de-duplicated by name and sorted alphabetically. When the same
 * name is found in multiple places, the copy best suited to `prefer` wins
 * (see `preferenceRank`); ties break by path so the result is deterministic
 * regardless of filesystem traversal order.
 */
export async function discoverSkills(
  rootDir: string,
  subpath?: string,
  prefer: SkillPreference = "templates",
): Promise<DiscoveredSkill[]> {
  const searchPath = subpath ? join(rootDir, subpath) : rootDir;
  const dirs = await findSkillDirs(searchPath);

  const byName = new Map<string, DiscoveredSkill>();
  for (const dir of dirs) {
    const skill = await readSkill(dir, rootDir);
    if (!skill) continue;

    const existing = byName.get(skill.name);
    if (!existing || isPreferred(skill, existing, prefer)) {
      byName.set(skill.name, skill);
    }
  }

  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** True when `candidate` should replace `current` for the same skill name. */
function isPreferred(
  candidate: DiscoveredSkill,
  current: DiscoveredSkill,
  prefer: SkillPreference,
): boolean {
  const candidateRank = preferenceRank(candidate.dir, prefer);
  const currentRank = preferenceRank(current.dir, prefer);
  if (candidateRank !== currentRank) return candidateRank > currentRank;
  // Same rank — pick the lexicographically lowest path for a stable result.
  return candidate.dir.localeCompare(current.dir) < 0;
}

/** Filter skills by user-supplied names (case-insensitive, matches name or dir basename). */
export function filterSkillsByName(skills: DiscoveredSkill[], names: string[]): DiscoveredSkill[] {
  const wanted = new Set(names.map((name) => normalizeSkillName(name)).filter(Boolean));
  return skills.filter(
    (skill) => wanted.has(skill.name) || wanted.has(normalizeSkillName(basename(skill.dir))),
  );
}
